export function pt(key) {
  const dict = getCurrentLanguage().startsWith('zh') ? zh : en;
  return dict[key] || en[key] || key;
}
export function publishError(message) {
  const key = (message || '').split(':')[0];
  return pt(key);
}
export function publishKey() {
  return Array.from(crypto.getRandomValues(new Uint8Array(16)), v => v.toString(16).padStart(2, '0')).join('');
}
